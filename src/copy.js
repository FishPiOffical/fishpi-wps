export function translator(locale) {
  const copy = /^zh(?:[-_]|$)/iu.test(locale) ? zh : en
  return (key, values = {}) => (copy[key] ?? en[key] ?? key)
    .replace(/\{(\w+)\}/gu, (match, name) => values[name] ?? match)
}
